// Package govern 是产品仓自己的治理薄本体（档案 §57）——只服务 go test，不进二进制语义。
//
// # 它是什么
//
// 本项目语境里「本体」一直是四层：词汇 / 类型 / 门 / 审计，无第五层推理机
// （§8.1）。本包给**治理域**补同样四层，对象是「裁决」而不是工作项：
//
//	词汇   执行类型五选一（见下）+ 引用关系（locks / hook / meter / review）
//	类型   档案节头 <!-- ruling: … --> 的字段
//	门     无（治理域不卡运行时写——卡点不变式）
//	审计   TestRulingLedger：每条裁决的结构完整性 + 纪律类到期即红
//
// 执行类型（enforcement）——一条裁决想让行为改变，只有这五种落点：
//
//	gate       写路径硬门：违规的写在发生时被拒
//	default    悲观默认：忘记 = 安全态（如 present 声明过期即 away）
//	meter      量尺：失效自己显形（如板仓 merge 提交 = 双写源指纹）
//	lock       行为锁：改坏即测试红（locks: 必须是真测试函数名）
//	hook       流程钩：在必经节点机械执行（如 pre-push 跑剧本）
//	discipline 纪律：靠读的人/模型照做——**会复发**，只许作为带量尺、带复审日的临时态
//
// # 为什么不是推理机本体
//
// 裁决失效不是因为知识不可读，而是「裁决 → 行为」之间没有执行连接：链上只要
// 有一环是「读者照做」，长期效力就趋零（presence 两轮、单写源、剧本必跑、§51
// 绳牛四代）。本体改变的是裁决的**表示**，不是裁决的**执行**；把档案散文换成
// OWL/SHACL 后，「谁来把裁决翻译成机制」这一步原样存在，还多出一份要维护的
// 实例库（与档案双源必漂移）。而最危险的三类失效——字符串锁当行为锁、量错尺、
// 入口漏盖——是语义判断，任何本体都判不了。所以：取本体的「词汇层」给校验器
// 用，不取推理层（基石否决项「Ontology reasoners」维持，§57 给出独立理由）。
//
// # 唯一剩下的纪律
//
// 「提交前跑 go test」。校验器、吞错锁都挂在它上面——这是全仓最根深蒂固的
// 动作，且 pre-push 钩子（.githooks/）再兜一层。再往上没有元规则可退：任何
// 「检查检查者」的规则自身又是文字（§57 反事实 5）。停止点就在这里。
